/**
 * SENTINEL AI - Gemini Evidence Explanation Service
 * Uses Google GenAI (gemini-3.8-flash) to synthesize and explain collected
 * forensic evidence for human SOC analysts without inventing detection results.
 */

import { GoogleGenAI } from '@google/genai';
import { ThreatFinding } from './heuristics';
import { ScoreAssessment } from './scoring';
import { ParsedUrlDetails } from './parser';

export interface GeminiExplanationResult {
  status: 'available' | 'unavailable';
  modelUsed?: string;
  summary?: string;
  riskAnalysis?: string;
  recommendedActions?: string[];
  rawExplanation?: string;
}

/**
 * Explains gathered forensic evidence using Gemini 3.8 Flash.
 */
export async function explainEvidenceWithGemini(
  parsedUrl: ParsedUrlDetails,
  scoring: ScoreAssessment,
  findings: ThreatFinding[]
): Promise<GeminiExplanationResult> {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey || apiKey === 'MY_GEMINI_API_KEY' || apiKey.trim() === '') {
    return {
      status: 'unavailable',
      rawExplanation:
        'Gemini Evidence Explainer: GEMINI_API_KEY is unconfigured in server environment. Configure a valid key in Settings > Secrets to enable automated generative analysis. Pure empirical forensics and heuristics are presented below.',
    };
  }

  const ai = new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });

  const prompt = `You are SENTINEL AI, a senior cybersecurity SOC analyst assistant. 
Analyze the following EMPIRICALLY COLLECTED threat intelligence evidence for target "${parsedUrl.normalizedUrl}".

IMPORTANT:
- Do NOT fabricate or invent detection results. Ground your explanation exclusively in the factual findings provided below.
- Explain clearly to a SOC analyst why these specific indicators are dangerous or benign.
- Be concise, objective, and professional.

--- EVIDENCE COLLECTED ---
Target URL: ${parsedUrl.normalizedUrl}
Hostname: ${parsedUrl.hostname}
TLD: .${parsedUrl.tld || 'N/A'}
Verdict: ${scoring.verdict} (Severity: ${scoring.severity.toUpperCase()})
Trust Score: ${scoring.trustScore}/100

FINDINGS:
${findings
  .map(
    (f, idx) =>
      `${idx + 1}. [${f.source}] ${f.title} (${f.severity.toUpperCase()}) - Evidence: ${f.evidence}\n   Description: ${f.description}`
  )
  .join('\n')}

--- INSTRUCTIONS ---
Provide your response in 3 structured sections:
1. Executive Risk Summary (1-2 sentences on what was detected)
2. Technical Threat Mechanics (Why the specific findings indicate malicious, suspicious, or legitimate intent)
3. Actionable Mitigation Steps (3 prioritized bullet points for incident responders)
`;

  // Timeout wrapper: 4.5 seconds maximum to keep investigation snappy
  const callWithTimeout = async (model: string) => {
    let timeoutHandle: NodeJS.Timeout;
    const timeoutPromise = new Promise<never>((_, reject) => {
      timeoutHandle = setTimeout(() => reject(new Error('Gemini API call timed out')), 4500);
    });

    const executionPromise = ai.models.generateContent({
      model,
      contents: prompt,
      config: {
        systemInstruction:
          'You are a cybersecurity expert explaining confirmed security telemetry. Maintain factual accuracy, avoid jargon overload, and never hallucinate findings.',
      },
    });

    return Promise.race([executionPromise, timeoutPromise]).finally(() => clearTimeout(timeoutHandle));
  };

  try {
    const response = await callWithTimeout('gemini-3.8-flash');
    const explanationText = response.text || 'No explanation generated by model.';

    return {
      status: 'available',
      modelUsed: 'gemini-3.8-flash',
      rawExplanation: explanationText,
    };
  } catch (err: any) {
    const errorMsg = err.message || '';
    // If timeout or permission error, don't attempt secondary slow fallback
    if (
      errorMsg.includes('timed out') ||
      errorMsg.includes('PERMISSION_DENIED') ||
      errorMsg.includes('API key') ||
      errorMsg.includes('403')
    ) {
      return {
        status: 'unavailable',
        rawExplanation:
          'Gemini Evidence Explainer currently offline (API timeout or unconfigured credentials). Pure empirical heuristics, DNS records, and threat feed results are presented.',
      };
    }

    // Attempt single fast fallback to gemini-flash-latest if 503 or model spike
    try {
      const fallbackResponse = await callWithTimeout('gemini-flash-latest');
      return {
        status: 'available',
        modelUsed: 'gemini-flash-latest',
        rawExplanation: fallbackResponse.text || 'Explanation generated via fallback model.',
      };
    } catch (fallbackErr: any) {
      return {
        status: 'unavailable',
        rawExplanation: `Gemini Evidence Explainer temporarily offline (${fallbackErr.message || errorMsg}). Displaying raw empirical threat telemetry.`,
      };
    }
  }
}
